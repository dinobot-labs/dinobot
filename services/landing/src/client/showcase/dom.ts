/** Small DOM helpers. CSP-safe: no style attributes in markup, no injected <style>; layout goes through CSSOM. */
import { type SpeciesId, isSpeciesId, renderMarkSvg } from "../../brand/mascot.ts";
import { DINO_EVENT, documentDino } from "../app/dino.ts";
import type { GlyphName } from "./scripts.ts";

export const SVG_NS = "http://www.w3.org/2000/svg";

export function h<K extends keyof HTMLElementTagNameMap>(tag: K, className?: string, text?: string): HTMLElementTagNameMap[K] {
	const el = document.createElement(tag);
	if (className) el.className = className;
	if (text !== undefined) el.textContent = text;
	return el;
}

export function s<K extends keyof SVGElementTagNameMap>(tag: K, attrs: Record<string, string | number> = {}): SVGElementTagNameMap[K] {
	const el = document.createElementNS(SVG_NS, tag);
	for (const [k, v] of Object.entries(attrs)) el.setAttribute(k, String(v));
	return el;
}

/** 5x5 dot glyphs on the mascot's grid (same construction as /design/ GLYPHS). */
export const GLYPHS: Readonly<Record<GlyphName, readonly string[]>> = {
	chat: ["#####", "#...#", "#...#", "#####", ".#..."],
	search: [".##..", "#..#.", "#..#.", ".##..", "....#"],
	branch: ["#...#", "#...#", "#..#.", "#.#..", "#...."],
	check: [".....", "....#", "...#.", "#.#..", ".#..."],
	plan: ["#....", "#.#..", "#####", "..#.#", "....#"],
	memory: ["#####", ".....", "#####", ".....", "#####"],
	assign: ["#....", ".#...", "..###", ".#...", "#...."],
	learn: ["....#", "...##", "..###", ".####", "#####"],
	ask: [".###.", "#...#", "...#.", "..#..", "..#.."],
	lock: [".###.", "#...#", "#####", "##.##", "#####"],
};

export function glyph(name: GlyphName, className = "sc-glyph"): SVGSVGElement {
	const svg = s("svg", { viewBox: "0 0 5 5", class: className, "aria-hidden": "true", focusable: "false" });
	GLYPHS[name].forEach((row, y) => {
		for (let x = 0; x < row.length; x++) if (row[x] === "#") svg.append(s("circle", { cx: x + 0.5, cy: y + 0.5, r: 0.38 }));
	});
	return svg;
}

const markMarkup = new Map<SpeciesId, string>();
const markupOf = (id: SpeciesId): string => {
	let markup = markMarkup.get(id);
	if (!markup) markMarkup.set(id, (markup = renderMarkSvg({ species: id })));
	return markup;
};
let markListener = false;

/** The dot-matrix head mark (src/brand) of the current dinosaur theme, as a decorative SVG element; follows theme changes. */
export function mark(className = "sc-mark"): HTMLElement {
	const span = h("span", className);
	span.innerHTML = markupOf(documentDino()); // trusted, generated by src/brand (fill attributes only, no style)
	span.setAttribute("aria-hidden", "true");
	span.dataset.scMark = "";
	if (!markListener) {
		markListener = true;
		window.addEventListener(DINO_EVENT, (event) => {
			const id = (event as CustomEvent<unknown>).detail;
			if (!isSpeciesId(id)) return;
			for (const node of document.querySelectorAll<HTMLElement>("[data-sc-mark]")) node.innerHTML = markupOf(id);
		});
	}
	return span;
}

/** Three loader dots (components.css .loader). */
export function loader(className = "loader"): HTMLElement {
	const el = h("span", className);
	el.setAttribute("aria-hidden", "true");
	el.append(h("i"), h("i"), h("i"));
	return el;
}

export function place(el: HTMLElement | SVGElement, x = 0, y = 0, w?: number, hh?: number): void {
	el.style.left = `${x}px`;
	el.style.top = `${y}px`;
	if (w !== undefined) el.style.width = `${w}px`;
	if (hh !== undefined) el.style.height = `${hh}px`;
}
